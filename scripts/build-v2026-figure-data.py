def inside(lon: float, lat: float, poly: list[tuple[float, float]]) -> bool:
    n = len(poly)
    hit = False
    j = n - 1
    for i in range(n):
        xi, yi = poly[i]
        xj, yj = poly[j]
        if ((yi > lat) != (yj > lat)) and (lon < (xj - xi) * (lat - yi) / (yj - yi + 1e-15) + xi):
            hit = not hit
        j = i
    return hit


def oisst_year(year: int) -> Path:
    dest = RAW / "oisst" / f"{year}.csv"
    if dest.exists() and dest.stat().st_size > 1000:
        return dest
    dest.parent.mkdir(parents=True, exist_ok=True)
    url = (
        "https://coastwatch.pfeg.noaa.gov/erddap/griddap/ncdcOisst21Agg_LonPM180.csv?"
        f"sst[({year}-06-01T12:00:00Z):1:({year}-10-31T12:00:00Z)][(0.0)]"
        "[(30.125):4:(45.125)][(-5.875):4:(36.125)]"
    )
    print("OISST", year)
    get(url, dest, timeout=180)
    return dest


def oisst_aug13(year: int) -> list[tuple[float, float, float]]:
    dest = RAW / "oisst" / f"aug13-{year}.csv"
    if not dest.exists() or dest.stat().st_size < 100:
        url = (
            "https://coastwatch.pfeg.noaa.gov/erddap/griddap/ncdcOisst21Agg_LonPM180.csv?"
            f"sst[({year}-08-13T12:00:00Z)][(0.0)]"
            "[(30.125):2:(45.125)][(-5.875):2:(36.125)]"
        )
        print("OISST aug13", year)
        get(url, dest, timeout=120)
    pts = []
    for line in dest.read_text(encoding="utf-8", errors="replace").splitlines()[2:]:
        parts = line.split(",")
        if len(parts) < 5:
            continue
        lat, lon, sst = float(parts[2]), float(parts[3]), parts[4]
        if sst == "NaN":
            continue
        pts.append((lon, lat, float(sst)))
    return pts


def basin_series(path: Path) -> list[float | None]:
    """Daily Mediterranean mean, 1 Jun–31 Oct, area-weighted, NaN if empty."""
    buckets: dict[str, list[tuple[float, float]]] = {}
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines()[2:]:
        parts = line.split(",")
        if len(parts) < 5 or parts[4] == "NaN":
            continue
        day, lat, lon, sst = parts[0][:10], float(parts[2]), float(parts[3]), float(parts[4])
        if not inside(lon, lat, MED):
            continue
        buckets.setdefault(day, []).append((lat, sst))
    days = sorted(buckets)
    out: list[float | None] = []
    for day in days:
        acc = 0.0
        wsum = 0.0
        for lat, sst in buckets[day]:
            w = math.cos(math.radians(lat))
            acc += sst * w
            wsum += w
        out.append(round(acc / wsum, 3) if wsum else None)
    return out


def build_oisst() -> None:
    years = list(range(1982, 2025))
    with ThreadPoolExecutor(max_workers=6) as pool:
        futures = [pool.submit(oisst_year, y) for y in years]
        for fut in as_completed(futures):
            fut.result()
    series = {str(y): basin_series(RAW / "oisst" / f"{y}.csv") for y in years}
    # climatology 1991–2020 on the common June–October length
    n = min(len(series[str(y)]) for y in range(1991, 2021))
    clim = []
    for i in range(n):
        vals = [series[str(y)][i] for y in range(1991, 2021) if series[str(y)][i] is not None]
        clim.append(round(sum(vals) / len(vals), 3) if vals else None)
    # anomaly map, 13 August, 0.5°
    aug_years = list(range(1991, 2021)) + [2024]
    with ThreadPoolExecutor(max_workers=6) as pool:
        aug = {y: pool.submit(oisst_aug13, y) for y in aug_years}
        aug = {y: fut.result() for y, fut in aug.items()}
    # align on rounded lon/lat
    def key(lon: float, lat: float) -> tuple[float, float]:
        return (round(lon, 3), round(lat, 3))

    clim_acc: dict[tuple[float, float], list[float]] = {}
    for y in range(1991, 2021):
        for lon, lat, sst in aug[y]:
            if inside(lon, lat, MED):
                clim_acc.setdefault(key(lon, lat), []).append(sst)
    anom = []
    for lon, lat, sst in aug[2024]:
        if not inside(lon, lat, MED):
            continue
        base = clim_acc.get(key(lon, lat))
        if not base:
            continue
        anom.append([round(lon, 3), round(lat, 3), round(sst - sum(base) / len(base), 2)])
    peak = max((v for v in series["2024"] if v is not None), default=None)
    peak_i = series["2024"].index(peak) if peak is not None else None
    write_ts(
        "oisst.ts",
        "medSst",
        {
            "years": years,
            "series": series,
            "climatology1991to2020": clim,
            "anomaly20240813": anom,
            "peak2024": peak,
            "peakIndexFromJune1": peak_i,
            "note": "Basin mean of NOAA OISST v2.1 over a Mediterranean polygon, 1° grid, cosine-weighted. Anomaly is 13 August 2024 minus the 13 August mean 1991–2020 on a 0.5° grid.",
        },
    )


