RAW.mkdir(parents=True, exist_ok=True)
OUT.mkdir(parents=True, exist_ok=True)

UA = {"User-Agent": "geofag-exam-figures/1.0 (educational; open-data redraw)"}


def get(url: str, dest: Path | None = None, timeout: int = 180) -> bytes:
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=timeout) as res:
        data = res.read()
    if dest is not None:
        dest.write_bytes(data)
    return data


def ts_string(name: str, payload: object) -> str:
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    return (
        "// Generated by scripts/build-v2026-figure-data.py. Do not edit by hand.\n"
        f"export const {name} = {body} as const;\n"
    )


def write_ts(filename: str, name: str, payload: object) -> None:
    path = OUT / filename
    path.write_text(ts_string(name, payload), encoding="utf-8")
    print(f"wrote {path} ({path.stat().st_size} bytes)")


