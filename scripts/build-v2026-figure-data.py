def fetch_etopo_slab(lat0: float, lat1: float, lon0: float, lon1: float, stride: int) -> list[tuple[float, float, float]]:
    # This ERDDAP grid stores longitude from 0 to 360.
    lon0 = lon0 % 360
    lon1 = lon1 % 360
    url = (
        "https://oceanwatch.pifsc.noaa.gov/erddap/griddap/ETOPO_2022_v1_60s.csv?"
        f"z[({lat0}):{stride}:({lat1})][({lon0}):{stride}:({lon1})]"
    )
    print("ETOPO", url)
    text = get(url).decode("utf-8", "replace")
    rows = []
    for line in text.splitlines()[2:]:
        parts = line.split(",")
        if len(parts) < 3:
            continue
        lat, lon, z = float(parts[0]), float(parts[1]), float(parts[2])
        if lon > 180:
            lon -= 360
        rows.append((lat, lon, z))
    return rows


def fetch_etopo(lat0: float, lat1: float, lon0: float, lon1: float, stride: int) -> dict:
    # Split slabs that cross the Greenwich meridian on a 0–360 axis.
    step = stride / 60.0
    if lon0 < 0 < lon1:
        rows = fetch_etopo_slab(lat0, lat1, lon0 % 360, 360 - step, stride)
        rows += fetch_etopo_slab(lat0, lat1, 0, lon1, stride)
    elif lon0 < 0:
        rows = fetch_etopo_slab(lat0, lat1, lon0 % 360, lon1 % 360, stride)
    else:
        rows = fetch_etopo_slab(lat0, lat1, lon0, lon1, stride)
    lats = sorted({round(r[0], 5) for r in rows}, reverse=True)
    lons = sorted({round(r[1], 5) for r in rows})
    lat_i = {v: i for i, v in enumerate(lats)}
    lon_i = {v: i for i, v in enumerate(lons)}
    grid = [0] * (len(lats) * len(lons))
    for lat, lon, z in rows:
        grid[lat_i[round(lat, 5)] * len(lons) + lon_i[round(lon, 5)]] = int(round(z))
    return {
        "lat0": lats[0],
        "lat1": lats[-1],
        "lon0": lons[0],
        "lon1": lons[-1],
        "ny": len(lats),
        "nx": len(lons),
        "z": grid,
        "source": "NOAA NCEI ETOPO 2022 v1, 60 arc-second ice surface",
    }


