def parse_nve(html: str) -> list[dict]:
    cells = re.findall(r"<td[^>]*>\s*(?:&nbsp;)?([0-9.\-]+)\s*</td>", html)
    rows = []
    for i in range(0, len(cells) - 3, 4):
        year = int(float(cells[i]))
        if year < 1900 or year > 2100:
            continue
        rows.append(
            {
                "year": year,
                "winter": float(cells[i + 1]),
                "summer": float(cells[i + 2]),
                "annual": float(cells[i + 3]),
            }
        )
    # The page repeats the table; keep the first contiguous run.
    dedup = []
    seen = set()
    for row in rows:
        if row["year"] in seen:
            break
        seen.add(row["year"])
        dedup.append(row)
    return dedup


def build_nve() -> None:
    alfot = (RAW / "nve-alfot.html").read_text(encoding="utf-8", errors="replace")
    hell = (RAW / "nve-hell.html").read_text(encoding="utf-8", errors="replace")
    if "Winter balance" not in alfot:
        alfot = get(
            "https://glacier.nve.no/Glacier/viewer/CI/en/nve/ClimateIndicatorInfo/2078?name=%C3%85lfotbreen"
        ).decode("utf-8", "replace")
    if "Winter balance" not in hell:
        hell = get(
            "https://glacier.nve.no/Glacier/viewer/CI/en/nve/ClimateIndicatorInfo/2768?name=Hellstugubreen"
        ).decode("utf-8", "replace")
    a = parse_nve(alfot)
    h = parse_nve(hell)
    print("NVE Ålfot", len(a), a[0]["year"], a[-1]["year"])
    print("NVE Hellstugu", len(h), h[0]["year"], h[-1]["year"])
    write_ts("nve.ts", "nveBalance", {"alfotbreen": a, "hellstugubreen": h})


