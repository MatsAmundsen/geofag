"""Download open datasets and write the TypeScript data for the v2026 exam figures.

Sources (all fetched at runtime, nothing is traced from Udir):
- ETOPO 2022, 60 arc-second, NOAA NCEI via ERDDAP
- NOAA OISST v2.1 daily, CoastWatch ERDDAP
- NCEP/NCAR reanalysis daily precipitable water and sea-level pressure, PSL
- NHC best track / tropical cyclone report for Hurricane Gabrielle (AL072025)
- NVE glacier mass balance (glacier.nve.no)
- EPICA Dome C temperature (Jouzel et al. 2007, NOAA Paleoclimatology)
- Spratt & Lisiecki 2016 sea-level stack (NOAA Paleoclimatology)
"""

