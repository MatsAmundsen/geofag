def parse_grid_ascii(text: str, var: str) -> tuple[list[float], list[float], list[list[float]]]:
    lats = [float(v) for v in re.search(r"lat\[\d+\]\n([0-9., \-]+)", text).group(1).split(",")]
    lons = [float(v) for v in re.search(r"lon\[\d+\]\n([0-9., \-]+)", text).group(1).split(",")]
    block = re.search(rf"{var}\.{var}\[\d+\]\[\d+\]\[\d+\]\n(.*?)(?:\n\n|\n{var}\.)", text, re.S)
    rows = []
    for line in block.group(1).strip().splitlines():
        nums = [float(v) for v in line.split(",")[1:]]
        rows.append(nums)
    return lats, lons, rows


def build_gyda() -> None:
    # North Atlantic–Europe window. Lat index: 90 - 2.5*i. Lon index: 2.5*j, 0..357.5.
    # lat 75N..40N -> index (90-75)/2.5=6 through (90-40)/2.5=20
    # lon 40W..50E -> 320E..50E, indices 128..20 wrapping. Fetch full lon, crop later.
    url_pw = (
        "https://psl.noaa.gov/thredds/dodsC/Datasets/ncep.reanalysis.dailyavgs/"
        "surface/pr_wtr.eatm.2022.nc.ascii?lat[6:1:22],lon[0:1:143],pr_wtr[11:1:11][6:1:22][0:1:143]"
    )
    url_slp = (
        "https://psl.noaa.gov/thredds/dodsC/Datasets/ncep.reanalysis.dailyavgs/"
        "surface/slp.2022.nc.ascii?lat[6:1:22],lon[0:1:143],slp[11:1:11][6:1:22][0:1:143]"
    )
    print("NCEP pr_wtr")
    pw_lats, pw_lons, pw = parse_grid_ascii(get(url_pw).decode(), "pr_wtr")
    print("NCEP slp")
    slp_lats, slp_lons, slp = parse_grid_ascii(get(url_slp).decode(), "slp")
    # SLP from NCEP is Pascals.
    slp_hpa = [[round(v / 100.0, 1) for v in row] for row in slp]
    pw_r = [[round(v, 2) for v in row] for row in pw]
    write_ts(
        "gyda.ts",
        "gyda",
        {
            "date": "2022-01-12",
            "lat": pw_lats,
            "lon": pw_lons,
            "precipitableWaterMm": pw_r,
            "slpHpa": slp_hpa,
        },
    )


