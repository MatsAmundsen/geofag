def build_paleo() -> None:
    epica_path = RAW / "edc.txt"
    if not epica_path.exists():
        get(
            "https://www.ncei.noaa.gov/pub/data/paleo/icecore/antarctica/epica_domec/edc3deuttemp2007.txt",
            epica_path,
        )
    epica = []
    for line in epica_path.read_text(encoding="utf-8", errors="replace").splitlines():
        parts = line.split()
        if len(parts) < 5:
            continue
        try:
            age_yr = float(parts[2])
            temp = float(parts[4])
        except ValueError:
            continue
        if age_yr < 0:
            continue
        epica.append((age_yr / 1000.0, temp))
    # Keep about one point per 0.5 ka so the file stays small.
    slim = []
    last = -999.0
    for age, temp in epica:
        if age >= last + 0.5 or age > 800:
            slim.append([round(age, 2), round(temp, 2)])
            last = age
    spratt_path = RAW / "spratt2016.txt"
    if not spratt_path.exists():
        get(
            "https://www.ncei.noaa.gov/pub/data/paleo/contributions_by_author/spratt2016/spratt2016.txt",
            spratt_path,
        )
    text = spratt_path.read_text(encoding="utf-8", errors="replace")
    print("--- spratt head ---")
    print("\n".join(text.splitlines()[:40]))
    sea = []
    for line in text.splitlines():
        parts = line.split()
        if len(parts) < 2:
            continue
        try:
            nums = [float(p) for p in parts[:4]]
        except ValueError:
            continue
        # Common layout: age_ka, sea_level_m, ...
        age, level = nums[0], nums[1]
        if 0 <= age <= 800 and -200 < level < 50:
            sea.append([round(age, 2), round(level, 2)])
    if len(sea) < 50:
        # Try other column orders later by printing a sample of numeric lines.
        print("sea-level parse short", len(sea))
        numeric = []
        for line in text.splitlines():
            parts = line.split()
            try:
                numeric.append([float(p) for p in parts])
            except ValueError:
                continue
            if len(numeric) > 8:
                break
        print("sample", numeric[:8])
    # subsample ~1 ka
    sea_slim = []
    last = -999.0
    for age, level in sea:
        if age >= last + 1:
            sea_slim.append([age, level])
            last = age
    write_ts(
        "paleo.ts",
        "paleo",
        {"epicaTempC": slim, "sprattSeaLevelM": sea_slim},
    )
    if sea_slim:
        window = [lv for age, lv in sea_slim if 450 <= age <= 750]
        print("sea level 750–450 ka min/max", min(window), max(window), "n", len(window))
        print("sea level near 0", [lv for age, lv in sea_slim if age < 2])


